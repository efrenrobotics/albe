export function isLand(lng: number, lat: number) {
  return COASTS.some((polygon) => {
    let inside = false;
    for (let i = 0, j = polygon.length - 2; i < polygon.length; j = i, i += 2) {
      const x = polygon[i];
      const y = polygon[i + 1];
      const lastX = polygon[j];
      const lastY = polygon[j + 1];
      if ((y > lat) !== (lastY > lat) && lng < (lastX - x) * (lat - y) / (lastY - y) + x) {
        inside = !inside;
      }
    }
    return inside;
  });
}
